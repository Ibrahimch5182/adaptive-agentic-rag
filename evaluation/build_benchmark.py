def _norm(s: str) -> str:
    """Docling PDF extraction sometimes inserts irregular multi-space runs between
    words (table-cell artifacts) — collapse whitespace so keyword matching is robust
    to that without being robust to genuine content differences."""
    return re.sub(r"\s+", " ", s)


def validate_against_dump():
    dump = json.loads(DUMP_PATH.read_text(encoding="utf-8"))
    # normalize dump keys (Windows backslash) -> basename
    by_basename: dict[str, list[dict]] = {}
    for path, chunks in dump.items():
        name = path.replace("\\", "/").rsplit("/", 1)[-1]
        by_basename[name] = chunks

    errors = []
    for item in QUESTIONS:
        if not item["answerable"]:
            continue
        all_text = _norm(" ".join(
            (c["raw_text"] + " " + c["section_title"]).lower()
            for doc in item["docs"] for c in by_basename.get(doc, [])
        ))
        for kw in item["keywords"]:
            if _norm(kw.lower()) not in all_text:
                errors.append(f"{item['id']}: keyword {kw!r} NOT FOUND in {item['docs']}")
    if errors:
        raise SystemExit("Ground-truth validation FAILED:\n" + "\n".join(errors))
    print(f"Validated {len(QUESTIONS)} questions against real parsed corpus — all keywords found.")


if __name__ == "__main__":
    validate_against_dump()
    OUT_PATH.write_text(json.dumps(QUESTIONS, indent=2, ensure_ascii=False), encoding="utf-8")
    n_answerable = sum(1 for q in QUESTIONS if q["answerable"])
    n_domains = len(set(q["domain"] for q in QUESTIONS))
    from collections import Counter
    cats = Counter(q["category"] for q in QUESTIONS)
    print(f"Wrote {len(QUESTIONS)} questions ({n_answerable} answerable, "
          f"{len(QUESTIONS)-n_answerable} unanswerable) across {n_domains} domains to {OUT_PATH}")
    print("Category breakdown:", dict(cats))
